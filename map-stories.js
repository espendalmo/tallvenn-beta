export function mapStorySeed(seed,key) {
  let hash=(seed??0)^0x811c9dc5;
  for (const letter of String(key)) hash=Math.imul(hash^letter.charCodeAt(0),0x01000193);
  return (hash^(hash>>>16))>>>0;
}

